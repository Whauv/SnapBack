// Copies the framework-agnostic runtime modules from packages/shared into the
// Meet extension, which has no bundler and loads raw ES modules. Run via
// `npm run sync:shared` at the repo root whenever packages/shared changes.
//
// Only dependency-free, platform-neutral modules belong here (no Vite
// `import.meta.env`, no `chrome.*`).

import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const sharedSrc = resolve(here, "../packages/shared/src");
const extensionDest = resolve(here, "../apps/meet-extension/src/shared");

const MODULES = ["formatters.js", "consent.js"];
const BANNER =
  "// GENERATED by scripts/sync-shared.mjs from packages/shared/src. Do not edit directly.\n\n";

mkdirSync(extensionDest, { recursive: true });

for (const moduleName of MODULES) {
  const source = readFileSync(resolve(sharedSrc, moduleName), "utf8");
  writeFileSync(resolve(extensionDest, moduleName), BANNER + source);
  console.log(`synced ${moduleName} -> apps/meet-extension/src/shared/${moduleName}`);
}
